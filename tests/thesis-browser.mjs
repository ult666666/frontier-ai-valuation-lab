  near('Alternative EV is calculated from the complete Bull case',await attr('#alternative-ev'),defaultCompare.alternative.result.ev);
  near('Signed gap equals the difference between both cases',await attr('#thesis-delta'),defaultCompare.evDelta);
  check('Waterfall exposes all six actual signed contributions',await page.locator('[data-thesis-contribution]').count(),6);
  for(const group of defaultCompare.attribution.groups)near(`${group.label} waterfall bar uses its exact allocation`,await attr(`[data-thesis-contribution="${group.key}"]`),group.contribution);
  check('All 26 model inputs have native accessible labels',await page.locator('[data-thesis-input]').evaluateAll(items=>items.length===26&&items.every(item=>item.labels.length>0&&item.getAttribute('aria-describedby'))));
  check('A 13 by 13 landscape contains 169 sampled points',await page.locator('[data-landscape-cell]').count(),169);
  check('Default landscape shows a solved target frontier',await page.locator('[data-frontier-point]').count()>0);
  check('Desktop has no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:`${qa}/desktop-top.png`,animations:'disabled'});
  await page.locator('#landscape-section').screenshot({path:`${qa}/landscape.png`,animations:'disabled'});

  const initial=await share();
  check('Denied clipboard access leaves a usable manual-copy fallback',await page.locator('#thesis-share-url').evaluate(item=>item.readOnly&&item.labels.length>0&&document.activeElement===item&&item.selectionStart===0&&item.selectionEnd===item.value.length));
  check('Shared default reference retains every exact input',initial.draft.reference.assumptions,presets.Anthropic.Base);
  check('Shared default alternative retains every exact input',initial.draft.alternative.assumptions,presets.Anthropic.Bull);
  await page.locator('#use-landscape-point').click();
  check('Applying the displayed default point is an exact no-op on the Bull assumptions',(await share()).draft.alternative.assumptions,presets.Anthropic.Bull);
  await page.locator('#swap-cases').click();
  near('Swapping cases reverses the entire signed gap',await attr('#thesis-delta'),-defaultCompare.evDelta);
  check('Changing cases clears a stale share link',await page.locator('#thesis-share-area').isHidden());
  await page.locator('#swap-cases').click();
  check('Swapping twice restores both exact cases',(await share()).draft,initial.draft);

  await page.locator('#assumption-editor').evaluate(item=>item.open=true);
  await page.locator('#alternative-g1').fill('');
  check('A blank assumption pauses the complete analysis',await page.locator('body').getAttribute('data-thesis-state'),'invalid');
  check('Invalid input disables sharing, brief and verification',await page.locator('#thesis-share').isDisabled()&&await page.locator('#thesis-brief').isDisabled()&&await page.locator('#thesis-verify').isDisabled());
  check('A blank assumption is exposed as invalid',await page.locator('#alternative-g1').getAttribute('aria-invalid'),'true');
  check('Invalid assumptions clear stale waterfall and surface cells',await page.locator('[data-thesis-contribution], [data-landscape-cell]').count(),0);
  await page.locator('#alternative-g1').fill('65');
  near('Fixing the assumption restores the correct result',await attr('#alternative-ev'),defaultCompare.alternative.result.ev);
  await page.locator('#alternative-g1').fill('64');
  await page.locator('#alternative-g1').fill('');
  await page.waitForTimeout(230);
  check('An invalid draft cancels any queued valid screen-reader result',(await page.locator('#thesis-announcement').innerText()).startsWith('Analysis paused.'));
  await page.locator('#alternative-g1').fill('65');
  await page.locator('#reference-preset').selectOption('Bull');
  near('Identical cases show a zero gap',await attr('#thesis-delta'),0);
  check('Identical cases retain six zero contributions',await page.locator('[data-thesis-contribution]').evaluateAll(items=>items.length===6&&items.every(item=>Number(item.dataset.value)===0)));

  const beforeRejectedImport=await share();
  const overflowingPair={...beforeRejectedImport.draft,reference:{scenario:'Base',assumptions:{...presets.Anthropic.Base,rev2026:1e-307,stub:0},bridge:null}};
  const overflowingLink=thesisUrl(url,overflowingPair);
  await page.evaluate(hash=>{location.hash=hash;},new URL(overflowingLink).hash);
  await page.locator('#thesis-notice.is-error').waitFor();
  check('A valid-endpoint import whose pair calculation overflows retains the previous analysis',await page.locator('body').getAttribute('data-thesis-state'),'ready');
  check('A rejected pair import cannot partially replace either case',(await share()).draft,beforeRejectedImport.draft);

  const exact={...presets.OpenAI.Base,g1:.4781234567890123,stub:-.123456789012345,wacc:.13750000000000004,m36:.26500000000000007};
  const bridge={cash:10.25,debt:2.5,otherClaims:.75};
  const portable={company:'OpenAI',scenario:'Base',assumptions:exact,bridge};
  await page.goto(scenarioUrl(url,portable),{waitUntil:'networkidle'});
  await page.locator('[data-thesis-state="ready"]').waitFor();
  let current=await share();
  check('A single-case link picks the matching company and named preset',current.draft.company,'OpenAI');
  check('The imported reference is the original named preset',current.draft.reference.assumptions,presets.OpenAI.Base);
  check('Single-case import retains all 13 exact custom values',current.draft.alternative.assumptions,exact);
  check('Single-case import retains its hypothetical bridge',current.draft.alternative.bridge,bridge);
  check('Custom assumptions are explicitly labeled',(await page.locator('#alternative-case-status').innerText()).includes('Edited'));
  const workbench=new URL(await page.locator('#alternative-open').getAttribute('href'));
  check('Open-in-model targets the original page',workbench.pathname.endsWith('/index.html'));
  check('Open-in-model carries the full exact case and bridge',decodeScenario(workbench.hash.slice('#scenario='.length)),portable);
  const reopened=await context.newPage();
  await reopened.goto(workbench.href,{waitUntil:'networkidle'});
  await reopened.locator('[data-result-ev]').waitFor();
  await reopened.locator('#share-scenario').click();
  await reopened.locator('#share-link-area:not([hidden])').waitFor();
  check('The actual original workbench restores and can reshare all exact inputs and bridge',decodeScenario(new URL(await reopened.locator('#share-url').inputValue()).hash.slice('#scenario='.length)),portable);
  await reopened.close();
  const fresh=await context.newPage();
  await fresh.goto(current.link,{waitUntil:'networkidle'});
  await fresh.locator('[data-thesis-state="ready"]').waitFor();
  check('A fresh two-case link restores its complete exact draft',(await share(fresh)).draft,current.draft);
  await fresh.close();

  const delayedContext=await browser.newContext({viewport:{width:1440,height:1100}});
  let releaseResearch,announceResearch;
  const researchGate=new Promise(resolve=>{releaseResearch=resolve;});
  const researchRequested=new Promise(resolve=>{announceResearch=resolve;});
  await delayedContext.route('**/data/research.json',async route=>{announceResearch();await researchGate;await route.continue();});
  const delayedPage=await delayedContext.newPage();
  await delayedPage.goto(initial.link,{waitUntil:'domcontentloaded'});
  await researchRequested;
  await delayedPage.evaluate(hash=>{location.hash=hash;},new URL(current.link).hash);
  releaseResearch();
  await delayedPage.locator('[data-thesis-state="ready"]').waitFor();
  check('A newer fragment during research loading restores the newest exact comparison',(await share(delayedPage)).draft,current.draft);
  await delayedContext.close();

  const selectedWindow=current.draft.landscape;
  const rateIndex=3,marginIndex=7;
  await page.locator('#landscape-rate-select').selectOption(String(rateIndex));
  await page.locator('#landscape-margin-select').selectOption(String(marginIndex));
  const selected={...exact,wacc:current.draft.landscape.rates[rateIndex],m36:current.draft.landscape.margins[marginIndex]};
  near('Native landscape controls select the actual two-input projection',await attr('#selected-point'),project(selected).ev);
  await page.locator('#use-landscape-point').click();
  current=await share();
  check('Use point changes exactly the two selected alternative assumptions',current.draft.alternative.assumptions,selected);
  check('Use point retains the optional bridge',current.draft.alternative.bridge,bridge);
  check('Use point preserves the shared landscape window',current.draft.landscape,selectedWindow);

  const sent=[];
  const capture=request=>{if(request.url().endsWith('/api/valuation')&&request.method()==='POST')sent.push(request.postDataJSON());};
  page.on('request',capture);
  await page.locator('#thesis-verify').click();
  await page.locator('#thesis-api-status.is-success').waitFor();
  check('Server verification submits both required analytic actions',sent.map(item=>item.action).sort(),['attribute','landscape']);
  check('Attribution API receives both exact current inputs',sent.find(item=>item.action==='attribute'),{action:'attribute',reference:current.draft.reference.assumptions,alternative:selected});
  check('Landscape API receives exact inputs, axes and target',sent.find(item=>item.action==='landscape'),{action:'landscape',assumptions:selected,...current.draft.landscape});
  page.off('request',capture);

  await page.route('**/api/valuation',async route=>{
    const body=route.request().postDataJSON();
    const result=body.action==='attribute'?compareTheses(body.reference,body.alternative):valuationLandscape(body.assumptions,{rates:body.rates,margins:body.margins,target:body.target});
    if(body.action==='attribute')result.alternative.result.rows[0].revenue+=1;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(wrapped(result))});
  });
  await page.locator('#thesis-verify').click();
  await page.locator('#thesis-api-status.is-error').waitFor();
  check('Verification detects a mismatched annual row even when EV agrees',(await page.locator('#thesis-api-status').innerText()).includes('match'));
  near('A verification mismatch retains local calculations',await attr('#alternative-ev'),project(selected).ev);
  await page.unroute('**/api/valuation');

  let release,seen;
  const gate=new Promise(resolve=>{release=resolve;});
  const requested=new Promise(resolve=>{seen=resolve;});
  await page.route('**/api/valuation',async route=>{seen();await gate;try{await route.continue();}catch{}});
  await page.locator('#thesis-verify').click();
  await requested;
  await page.locator('#alternative-preset').selectOption('Bear');
  release();
  await page.unroute('**/api/valuation');
  await page.waitForTimeout(250);
  check('Changing cases prevents a pending verification from certifying stale inputs',!(await page.locator('#thesis-api-status').getAttribute('class')).includes('is-success'));

  await page.locator('#landscape-window').evaluate(item=>item.open=true);
  await page.locator('#window-wacc-min').fill('');
  check('A blank landscape bound suppresses stale analytic outputs',await page.locator('body').getAttribute('data-thesis-state'),'invalid');
  check('Invalid landscape window pauses exports and verification',await page.locator('#thesis-brief').isDisabled()&&await page.locator('#thesis-verify').isDisabled());
  await page.locator('#window-wacc-min').fill('7.5');
  await page.locator('#landscape-target').fill('0');
  check('Zero target EV is explicitly invalid',await page.locator('body').getAttribute('data-thesis-state'),'invalid');
  await page.locator('#landscape-target').fill('500');
  await page.locator('[data-thesis-state="ready"]').waitFor();
  await page.locator('#thesis-company').selectOption('Anthropic');
  check('Company changes reset the two named cases',await Promise.all(['reference','alternative'].map(side=>page.locator(`#${side}-preset`).inputValue())),['Base','Bull']);
  await page.locator('#alternative-preset').selectOption('Bear');
  check('Negative EV remains a signed dollar result',await attr('#alternative-ev')<0);
  current=await share();
  const downloadPending=page.waitForEvent('download');
  await page.locator('#thesis-brief').click();
  const download=await downloadPending;
  const briefPath=`${qa}/current-thesis-brief.html`;
  await download.saveAs(briefPath);
  const brief=await readFile(briefPath,'utf8');
  check('The downloaded current comparison brief contains no scripts',!/<script\b|\son\w+\s*=/i.test(brief));
  check('The comparison brief contains the current reopening link',brief.includes(new URL(current.link).hash.slice(1)));

