  check('Presentation mode hides editing controls',await page.locator('#assumption-editor').isHidden());
  check('Presentation mode retains visible current values and its exit',await page.locator('#reference-ev').isVisible()&&await page.locator('#presenter-toggle').isVisible());
  await page.screenshot({path:`${qa}/presenter.png`,animations:'disabled'});
