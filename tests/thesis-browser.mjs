  check('Exiting presentation restores editing',await page.locator('#assumption-editor').isVisible());
  const previousRateIndex=Number(await page.locator('#landscape-rate-select').inputValue());
  const rateCount=await page.locator('#landscape-rate-select option').count();
  await page.locator('#landscape-rate-select').focus();
  await page.keyboard.press('ArrowDown');
